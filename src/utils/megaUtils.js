// 逆引き用（メガ形態 -> 通常形態）
export const REVERSE_MEGA_MAP = {};
Object.entries(MEGA_MAP).forEach(([base, megas]) => {
  megas.forEach((mega) => {
    REVERSE_MEGA_MAP[mega] = base;
  });
});

/**
 * 技リスト参照用：メガシンカ前のポケモン名を取得
 */
export const getBasePokemonName = (name) => {
  if (!name) return "";
  if (REVERSE_MEGA_MAP[name]) {
    return REVERSE_MEGA_MAP[name];
  }
  return name.replace(/^メガ/, "");
};

/**
 * メガシンカ候補の配列を取得（例: リザードン -> ["メガリザードンX", "メガリザードンY"]）
 */
export const getMegaForms = (name) => {
  if (!name) return [];
  const baseName = getBasePokemonName(name);
  return MEGA_MAP[baseName] || [];
};